    private fun Class<out Serializable>.checkProxied() {
        // ANY-ACCESS-MODIFIER Object writeReplace() throws ObjectStreamException;
        val writeReplace = checkDeclaresMethod("writeReplace", Object::class.java)
        // private is not strictly required TODO ref / explanation
        writeReplace.checkModifiers(PRIVATE)
        writeReplace.checkThrows(ObjectStreamException::class.java)

        // private void readObject(java.io.ObjectInputStream in) throws IOException, ClassNotFoundException;
        // todo explain (always throw)
        val readObject = checkDeclaresMethod("readObject", Void.TYPE, ObjectInputStream::class.java)
        readObject.checkModifiers(PRIVATE)
        readObject.checkThrows(IOException::class.java, ClassNotFoundException::class.java)

        if (isFinal(modifiers)) {
            checkDoesntHaveMethod(
                "readObjectNoData",
                reason = "This method is ignored for classes that can't be extended. It can safely be removed.",
            )
        } else {
            // private void readObjectNoData() throws ObjectStreamException;
            val readObjectNoData = checkDeclaresMethod("readObjectNoData", Void.TYPE)
            readObjectNoData.checkModifiers(PRIVATE)
            readObjectNoData.checkThrows(ObjectStreamException::class.java)
        }

        // todo is this true?
        checkDoesntHaveMethod(
            "writeObject",
            reason = "This method is ignored for classes that declare a writeReplace method. It can safely be removed.",
        )
        checkDoesntHaveMethod(
            "readResolve",
            reason = "It is unlikely that a proxied class needs to replace itself during deserialization. If it " +
                "does, you might want to adjust JvmSerializableClassesTest.",
        )
    }

