private val printSerializableClasses = object : SimpleFileVisitor<Path>() {
    override fun visitFile(file: Path, attrs: BasicFileAttributes): FileVisitResult {
        val fileName = file.fileName.toString()
        if (!fileName.endsWith(".class") || fileName == "module-info.class") {
            return FileVisitResult.CONTINUE
        }
        val binaryName = buildString {
            file.parent?.forEach { append(it).append('.') }
            append(fileName, 0, fileName.lastIndexOf('.'))
        }
        val currentLoader = javaClass.classLoader
        val clazz = Class.forName(binaryName, false, currentLoader)
        if (!Serializable::class.java.isAssignableFrom(clazz) || Enum::class.java.isAssignableFrom(clazz)) {
            return FileVisitResult.CONTINUE
        }
        print("${clazz.name} extends ${clazz.superclass.name}")
        val interfaces = clazz.interfaces
        if (interfaces.size > 0) {
            print(interfaces.joinToString(", ", " implements ") { it.name })
        }
        println()
        return FileVisitResult.CONTINUE
    }
}

fun main(vararg args: String) {
    val jar = Path(args[0])
    FileSystems.newFileSystem(jar, null as ClassLoader?).use { fs ->
        fs.rootDirectories.forEach { root -> Files.walkFileTree(root, printSerializableClasses) }
    }
}
