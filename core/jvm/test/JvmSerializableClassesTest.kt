    )

    private data class SerCl(
        val clazz: KClass<out Serializable>,
        val expectedSerialVersionUID: Long,
        val pattern: Pattern,
    ) {
        enum class Pattern {
            /** @see JvmSerializableClassesTest.checkProxy */
            PROXY,

            /** @see JvmSerializableClassesTest.checkProxied */
            PROXIED,

            /** @see JvmSerializableClassesTest.checkException */
            EXCEPTION, // todo split this up?
        }
    }

    @Test
    fun foo() {
        serializableClasses.forEach { (clazz, expectedSerialVersionUID, mode) ->
            val javaClass = clazz.java
            javaClass.checkIs<Serializable>()
            javaClass.checkDeclaresSerialVersionUID(expectedSerialVersionUID)
            javaClass.checkDoesntDeclareSerialPersistentFields()
            when (mode) {
                PROXY -> javaClass.checkProxy()
                PROXIED -> javaClass.checkProxied()
                EXCEPTION -> javaClass.checkException()
            }
        }
    }

    private inline fun <reified T> Class<out Serializable>.checkIs() {
        assertTrue(
            T::class.java.isAssignableFrom(this),
            message = "$this is no longer a subtype of ${T::class.simpleName}. You might want to adjust " +
                "JvmSerializableClassesTest.",
        )
    }

    private fun Member.checkModifiers(vararg expectedModifiers: Int) {
        var expected = expectedModifiers.fold(0, Int::or)
        var actual = modifiers
        if (isPrivate(expected) && this is Method) {
            // kotlin adds final to private methods, ignore it
            expected = expected and FINAL.inv()
            actual = actual and FINAL.inv()
        }
        assertEquals(
            expected, actual,
            message = "$declaringClass: $name must be '${toString(expected)}' but was '${toString(actual)}'.",
        )
    }

    private fun Class<out Serializable>.checkDeclaresMethod(
        name: String,
        returnType: Class<*>,
        vararg parameterTypes: Class<*>,
    ): Method {
        // don't use getDeclaredMethod(String name, Class<?>... parameterTypes), it can't handle multiple methods with
        // the same parameter types but a different return type as would be generated by code like this:
        // fun a(): Int = 0
        // @JvmName("a") fun b(): Long = 0
        declaredMethods
            .filter { it.name == name }
            .ifEmpty { fail("$this is missing $name. Was it misspelled?") }
            .firstOrNull { it.returnType == returnType && it.parameterTypes.contentEquals(parameterTypes) }
            ?.let { return it }

        val params = parameterTypes.joinToString { it.kotlin.simpleName.toString() }
        val sig = "fun $name($params): ${returnType.kotlin.simpleName}"
        if (returnType.isPrimitive) fail("$this has a wrong signature for $name, must be $sig")
        fail("$this has a wrong signature for $name, must be $sig or $sig?")
    }


    private fun Method.checkThrows(vararg expectedExceptionTypes: Class<out Exception>) {
        assertEquals(
            expectedExceptionTypes.toSet(), actual = exceptionTypes.toSet(),
            message = "$declaringClass: $name throws the wrong exception types."
        )
    }

    private fun Class<out Serializable>.checkDeclaresSerialVersionUID(expectedSerialVersionUID: Long) {
        // ANY-ACCESS-MODIFIER static final long serialVersionUID = 42L;
        val serialVersionUID = try {
            getDeclaredField("serialVersionUID")
        } catch (e: NoSuchFieldException) {
            fail(
                message = "$this is missing serialVersionUID. All serializable classes should explicitly declare " +
                    "their serialVersionUID. See " +
                    "https://docs.oracle.com/en/java/javase/24/docs/specs/serialization/class.html#stream-unique-identifiers",
                cause = e,
            )
        }
        // private is not strictly required TODO ref / explanation
        serialVersionUID.checkModifiers(PRIVATE, STATIC, FINAL)
        assertEquals(
            expected = java.lang.Long.TYPE, actual = serialVersionUID.type,
            message = "$this: serialVersionUID must be long.",
        )

        serialVersionUID.isAccessible = true
        assertEquals(
            expectedSerialVersionUID, actual = serialVersionUID.get(null),
            message = "$this: serialVersionUID changed. This means trying to deserialize previously serialized " +
                "instances of this class will now fail with InvalidClassException. Try versioning this class " +
                "differently instead. See " +
                "https://docs.oracle.com/en/java/javase/24/docs/specs/serialization/version.html",
        )
    }

    private fun Class<out Serializable>.checkDoesntDeclareSerialPersistentFields() {
        try {
            getDeclaredField("serialPersistentFields")
        } catch (_: NoSuchFieldException) {
            return // expected
        }
        if (Externalizable::class.java.isAssignableFrom(this)) {
            fail(
                "$this declares serialPersistentFields. This field is ignored for classes that implement " +
                    "Externalizable. It can safely be removed."
            )
        } else {
            fail(
                // TODO
                """
                $this: Java Object Serialization should.
                
                See JvmSerializableClassesTest for the patterns that should be used to implement Java Object Serialization.
            """.trimIndent()
            )
        }
    }

    private fun Class<out Serializable>.checkDoesntHaveMethod(name: String, reason: String) {
        // don't bother to check the signature, this might lead to false positives though
        if (declaredMethods.any { it.name == name }) {
            fail("$this declares $name. $reason")
        }
    }

    /**
     * Check the TODO java ser
     *
     * ```
     * @PublishedApi // keep it in the ABI dump to ensure the name of the class isn't changed
     * internal class SerializationProxy internal constructor(...) : java.io.Externalizable {
     *
     *     // public no-arg constructor used by deserialization
     *     constructor() : this(...)
     *
     *     override fun writeExternal(oo: java.io.ObjectOutput) {
     *         // ...
     *         TODO()
     *     }
     *
     *     override fun readExternal(oi: java.io.ObjectInput) {
     *         // ...
     *         TODO()
     *     }
     *
     *     // might also return Any?
     *     @Throws(java.io.ObjectStreamException::class)
     *     private fun readResolve(): Any = SerializationProxied(...)
     *
     *     private companion object {
     *         private const val serialVersionUID: Long = 0L
     *     }
     * }
     * ```
     *
     * @see kotlinx.datetime.Ser
     */
    private fun Class<out Serializable>.checkProxy() {
        checkIs<Externalizable>()

        val noArgConstructor = try {
            getDeclaredConstructor()
        } catch (e: NoSuchMethodException) {
            fail(
                message = "$this does not declare the no-arg constructor which required for classes that implement " +
                    "Externalizable.",
                cause = e
            )
        }
        noArgConstructor.checkModifiers(PUBLIC)

        // Don't check writeExternal and readExternal, the compiler already does that. They are just normal abstract
        // interface methods and must be overridden by classes that implement Externalizable.

        // ANY-ACCESS-MODIFIER Object readResolve() throws ObjectStreamException;
        val readResolve = checkDeclaresMethod("readResolve", Object::class.java)
        // private is not strictly required TODO ref / explanation
        readResolve.checkModifiers(PRIVATE)
        readResolve.checkThrows(ObjectStreamException::class.java)

        checkDoesntHaveMethod(
            "writeReplace",
            reason = "It is unlikely that a serialization proxy needs to replace itself during serialization. If it " +
                "does, you might want to adjust JvmSerializableClassesTest.",
        )

        val ignoredReason =
            "This method is ignored for classes that implement Externalizable. It can safely be removed."
        checkDoesntHaveMethod("writeObject", ignoredReason)
        checkDoesntHaveMethod("readObject", ignoredReason)
        checkDoesntHaveMethod("readObjectNoData", ignoredReason)
    }

