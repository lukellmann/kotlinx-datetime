        SerCl(kotlinx.datetime.LocalDateTime::class, -4261744960416354711L, PROXIED), // todo
        SerCl(kotlinx.datetime.LocalTime::class, -352249606036216323L, PROXIED), // todo
        SerCl(kotlinx.datetime.UtcOffset::class, -6636773355667981618L, PROXIED), // todo
        SerCl(kotlinx.datetime.Ser::class, 0L, PROXY),
        SerCl(kotlinx.datetime.DateTimeArithmeticException::class, -3207806170214997982L, EXCEPTION),
        SerCl(kotlinx.datetime.IllegalTimeZoneException::class, 1159315966274264801L, EXCEPTION),
